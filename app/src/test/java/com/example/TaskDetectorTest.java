package com.example;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;

import java.util.ArrayList;
import java.util.List;

import org.junit.Test;

/** Что считается задачей, а что просто разговором: поручения находятся, рассуждения и лекционные обороты нет. */
public class TaskDetectorTest {
    private static List<Task> detect(String text) {
        List<Segment> segments = new ArrayList<>();
        segments.add(Segment.of(0, 1000, 0, text));
        return TaskDetector.detect(segments);
    }

    @Test public void realTasksAreFound() {
        String[] tasks = {
            "Я отправлю тебе файл завтра.",
            "Мне надо купить хлеб.",
            "Договорились, что ты пришлёшь презентацию до вторника.",
            "Давайте созвонимся завтра.",
            "Нужно подготовить отчёт до конца недели.",
            "Иван, ты должен отправить договор до пятницы.",
            "Не забудь написать письмо заказчику.",
            "Надо будет оплатить счёт до 15 ноября.",
            "Я уточню у заказчика сроки до пятницы.",
            "Нужно сдать курсовую к понедельнику.",
            "Мы организуем встречу на следующей неделе.",
            "Позвоню клиенту завтра утром.",
            "Завтра отправлю тебе таблицу с расчётами.",
            "Нужно позвонить в банк и узнать про справку.",
            "Оля, нужно заказать билеты на пятницу.",
            "Договорились: Саша пришлёт договор до конца дня.",
            "Мы с тобой должны сдать лабораторную в понедельник.",
            "Я скину вам презентацию вечером.",
            "Петя, подготовь отчёт до среды.",
            "Надо записать Ивана на встречу в четверг."
        };
        for (String text : tasks) {
            assertEquals("Должно быть задачей: " + text, 1, detect(text).size());
        }
    }

    @Test public void discussionIsNotATask() {
        String[] talk = {
            "Сейчас проверим другие стороны этой точки зрения.",
            "Надо подумать над этим.",
            "Нужно понимать, что функция здесь непрерывна.",
            "Для этого нужно сделать замену переменной.",
            "Надо отметить, что результат получился неожиданным.",
            "Давайте посмотрим на график.",
            "Давайте рассмотрим следующий пример.",
            "Теперь обсудим, как это работает.",
            "Если бы нужно было, мы бы отправили.",
            "Не надо отправлять отчёт сегодня.",
            "Нужно ли сделать отчёт?",
            "Обычно нужно сделать проверку входных данных.",
            "Надо проверить гипотезу.",
            "Здесь нужно учитывать начальные условия.",
            "Нужно сказать несколько слов о методе.",
            "Мы это ещё обсудим, наверное.",
            "Потом посмотрим, что получится.",
            "Надо сказать, что это не всегда работает.",
            "Нужно взять производную по x и приравнять к нулю.",
            "Давайте проверим этот результат на примере.",
            "Мы разберём эту тему на следующей лекции.",
            "Сейчас я покажу, как это делается.",
            "Как правило, нужно подготовить данные заранее.",
            "Тут надо быть осторожным.",
            "Мне нужно понять, как это работает.",
            "Нужно было сделать это раньше.",
            "Решим это уравнение методом подстановки.",
            "Допустим, мы отправим запрос на сервер.",
            "Вы должны понимать разницу между этими понятиями.",
            "Хорошо, понятно."
        };
        for (String text : talk) {
            assertEquals("Не должно быть задачей: " + text, 0, detect(text).size());
        }
    }

    @Test public void twoObligationsInOneSentenceAreSplit() {
        List<Task> tasks = detect("Нужно сделать проект к пятнице, нужно сделать домашнее задание.");
        assertEquals(2, tasks.size());
        assertEquals("Пятнице".toLowerCase(), tasks.get(0).deadline.replace("к ", "").toLowerCase());
        assertEquals("", tasks.get(1).deadline);
    }

    @Test public void deadlineIsExtracted() {
        List<Task> tasks = detect("Нужно подготовить отчёт до конца недели.");
        assertEquals(1, tasks.size());
        assertTrue(tasks.get(0).deadline.contains("конца недели"));
    }
}
